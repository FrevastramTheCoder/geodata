function slugify(value) {
  return value
    .normalize("NFKD")
    .replace(/[^\w\s-]/g, "")
    .trim()
    .toLowerCase()
    .replace(/[\s_-]+/g, "-");
}

function createCourse(category, item, index) {
  const source = typeof item === "string" ? { title: item } : item;
  const title = source.title;
  const skills = source.skills || [
    `Apply ${title} methods to a geospatial workflow`,
    "Prepare and validate relevant spatial data",
    "Communicate practical findings clearly",
  ];
  const tools = source.tools || category.tools;

  return {
    slug: source.slug || `${category.id}-${slugify(title)}`,
    title,
    description:
      source.description ||
      `${title} is a practical pathway in ${category.name.toLowerCase()}, with guided exercises and a project-based outcome.`,
    instructor: "GeoBrains Academy",
    category: category.name,
    categoryId: category.id,
    categoryDescription: category.description,
    categoryIcon: category.icon,
    level: source.level || LEVELS[index % LEVELS.length],
    practicalProject:
      source.project ||
      `Complete a portfolio-ready ${title.toLowerCase()} case study using a realistic geospatial dataset.`,
    tools,
    skills,
    duration: source.duration || "Duration to be announced",
    accessType: source.accessType || (source.featured ? "Paid" : "Free"),
    certificate: source.certificate || "Academy certificate pathway (planned)",
    careerTracks: source.careerTracks || CATEGORY_TRACKS[category.id] || [],
    technologyTags: source.technologyTags || tools,
    certificateAvailable: false,
    learningObjectives: skills,
    lessons: source.lessons || [`${title} concepts`, "Guided workflow", "Practical project"],
    featured: Boolean(source.featured),
    popular: Boolean(source.popular),
    isNew: Boolean(source.isNew),
  };
}

export const COURSE_CATEGORIES = CATEGORY_DEFINITIONS.map(({ courses, ...category }) => category);

export const TRAINING_RESOURCES = CATEGORY_DEFINITIONS.flatMap((category) =>
  category.courses.map((course, index) => createCourse(category, course, index)),
);

export function getTraining(slug) {
  return TRAINING_RESOURCES.find((course) => course.slug === slug) || null;
}
